export function galleryAltTextsFor(albumSlug: string, photoCount: number): readonly string[] {
  const altTexts = galleryAltTexts[albumSlug as keyof typeof galleryAltTexts];
  if (!altTexts) {
    throw new Error(`Galeri albümü için alternatif metin bulunamadı: ${albumSlug}`);
  }
  if (altTexts.length !== photoCount) {
    throw new Error(
      `${albumSlug} albümündeki alternatif metin sayısı (${altTexts.length}), fotoğraf sayısıyla (${photoCount}) eşleşmiyor.`,
    );
  }
  return altTexts;
}
